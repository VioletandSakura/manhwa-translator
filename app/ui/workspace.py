def hint(text: str) -> QLabel:
    label = QLabel(text)
    label.setObjectName("hintText")
    label.setWordWrap(True)
    return label


def stack_field(title: str, widget: QWidget) -> QWidget:
    container = QWidget()
    layout = QVBoxLayout(container)
    layout.setContentsMargins(0, 0, 0, 0)
    layout.setSpacing(6)
    label = QLabel(title)
    label.setObjectName("fieldLabel")
    label.setBuddy(widget)
    widget.setAccessibleName(title)
    layout.addWidget(label)
    layout.addWidget(widget)
    return container


def separator() -> QFrame:
    line = QFrame()
    line.setObjectName("separator")
    return line


def scroll_content(content: QWidget) -> QScrollArea:
    scroll = QScrollArea()
    scroll.setWidgetResizable(True)
    scroll.setFrameShape(QFrame.Shape.NoFrame)
    scroll.setHorizontalScrollBarPolicy(Qt.ScrollBarPolicy.ScrollBarAlwaysOff)
    scroll.setWidget(content)
    scroll.setMinimumSize(0, 0)
    return scroll


def column(parent: QWidget, margins: int = 20) -> QVBoxLayout:
    layout = QVBoxLayout(parent)
    layout.setContentsMargins(margins, margins, margins, margins)
    layout.setSpacing(16)
    return layout


def table(columns: list[str], empty: str) -> EmptyTable:
    widget = EmptyTable(len(columns), empty)
    widget.setHorizontalHeaderLabels(columns)
    widget.verticalHeader().hide()
    widget.verticalHeader().setDefaultSectionSize(42)
    widget.setShowGrid(False)
    widget.setSelectionBehavior(QAbstractItemView.SelectionBehavior.SelectRows)
    widget.setSelectionMode(QAbstractItemView.SelectionMode.SingleSelection)
    widget.setEditTriggers(QAbstractItemView.EditTrigger.NoEditTriggers)
    widget.horizontalHeader().setStretchLastSection(True)
    widget.setMinimumSize(0, 100)
    widget.setSizePolicy(QSizePolicy.Policy.Expanding, QSizePolicy.Policy.Expanding)
    return widget


